r"""Write the window's slider rows, tooltips and menu names from gui.py as Rust constants.

  .venv\Scripts\python.exe rust\tools\export_gui_texts.py

Generates rust/src/bin/app/specs.rs, so the Korean keys the Rust window looks up are the
Python window's to the character. Run it again when those tables in gui.py change.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import gui  # noqa: E402


def rust(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)  # a JSON string is a valid Rust string literal here


def specs(name: str, rows) -> str:
    lines = [f"pub const {name}: [Spec; {len(rows)}] = ["]
    for key, label, low, high, scale, unit in rows:
        lines.append(f"    Spec {{ key: {rust(key)}, label: n_({rust(label)}), low: {float(low)!r}, high: {float(high)!r}, "
                     f"scale: {float(scale)!r}, unit: {rust(unit)} }},")
    lines.append("];")
    return "\n".join(lines)


def main() -> None:
    out = [
        "//! Generated by rust/tools/export_gui_texts.py from gui.py: the slider rows, their tooltips and",
        "//! the menus' names, keyed by the Korean text as in i18n.py. Do not edit by hand.",
        "",
        "use ats_haptics::i18n::n_;",
        "",
        "/// key, label, slider range, slider units per gain unit, unit text",
        "pub struct Spec {",
        "    pub key: &'static str,",
        "    pub label: &'static str,",
        "    pub low: f64,",
        "    pub high: f64,",
        "    pub scale: f64,",
        "    pub unit: &'static str,",
        "}",
        "",
        specs("OUTPUT_SLIDERS", gui.OUTPUT_SLIDERS),
        specs("EFFECT_SLIDERS", gui.EFFECT_SLIDERS),
        specs("EVENT_SLIDERS", gui.EVENT_SLIDERS),
        specs("THRESHOLD_SLIDERS", gui.THRESHOLD_SLIDERS),
        "",
        f"pub const CARD_WIDE: [&str; {len(gui.CARD_WIDE)}] = [{', '.join(rust(k) for k in gui.CARD_WIDE)}];",
        "",
        f"pub const SLIDER_TIPS: [(&str, &str); {len(gui.SLIDER_TIPS)}] = [",
        *(f"    ({rust(k)}, n_({rust(v)}))," for k, v in gui.SLIDER_TIPS.items()),
        "];",
        "",
        f"pub const SURFACE_NAMES: [(&str, &str); {len(gui.SURFACE_NAMES)}] = [",
        *(f"    ({rust(k)}, n_({rust(v)}))," for k, v in gui.SURFACE_NAMES.items()),
        "];",
        "",
        f"pub const DRIVES: [(&str, &str); {len(gui.DRIVES)}] = [",
        *(f"    ({rust(k)}, n_({rust(v)}))," for k, v in gui.DRIVES.items()),
        "];",
        "",
        f"pub const CYLINDERS_RANGE: (i64, i64) = {gui.CYLINDERS_RANGE!r};",
        "",
    ]
    path = ROOT / "rust" / "src" / "bin" / "app" / "specs.rs"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"-> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
